// features/ql_hit_marker/manifest.js
// =============================================================================
// QOLLOCK — Custom Hit Marker
// =============================================================================
// OWNS:        Root HUD classes qol-hm-* that select the generated hit marker rules in
//              styles/ability_hud_elements/element_gun.css (length, crit length,
//              thickness, spacing, colors, outline shadow, crit glow).
// DOES NOT OWN: Native hit marker panels and their show/hide logic (Valve);
//              the citadel_crosshair_hit_marker_duration on/off in the Console tab.
// DEPENDS ON:  QOL.core.FeatureRegistry
// CONFIG KEYS: ENABLE_CUSTOM_HITMARKER, CUSTOM_HITMARKER_SIZE, CUSTOM_HITMARKER_CRIT_SIZE,
//              CUSTOM_HITMARKER_THICKNESS, CUSTOM_HITMARKER_OFFSET, CUSTOM_HITMARKER_COLOR,
//              CUSTOM_HITMARKER_CRIT_COLOR, ENABLE_CUSTOM_HITMARKER_SHADOW,
//              ENABLE_CUSTOM_HITMARKER_HIDE_GLOW
// CSS:         generated by scripts/generate_hit_marker_css.js; the ranges below must match it
// PATTERN:     Class toggles on settings change only. No polling, no per-frame work, no
//              panel searches. A value equal to the native hit marker adds no class.
// =============================================================================

(function() {
    "use strict";
    var FR = QOL.core.FeatureRegistry;
    if (!FR) { $.Msg("[QOLLock] ql_hit_marker: FeatureRegistry not found — aborting"); return; }

    // "def" is the native hit marker (20px long, 2px thick, 40px from center), so a
    // value at its default needs no class and the stock rules apply.
    var LENGTH = { min: 4, max: 40, step: 1, def: 20 };
    var THICKNESS = { min: 1, max: 8, step: 1, def: 2 };
    var OFFSET = { min: 4, max: 40, step: 1, def: 40 };
    var PALETTE_MAX = 29;

    function _isTrue(v) { return v === true || v === 1 || String(v) === "true"; }

    // Clamp to the range and snap to the step grid so the result always has a generated rule.
    function _int(v, lim) {
        var n = Math.round(Number(v));
        if (!isFinite(n)) return lim.def;
        if (n < lim.min) n = lim.min;
        if (n > lim.max) n = lim.max;
        return lim.min + Math.round((n - lim.min) / lim.step) * lim.step;
    }

    function _palette(v) {
        var n = Math.round(Number(v));
        return (!isFinite(n) || n < 0 || n > PALETTE_MAX) ? 0 : n;
    }

    function desiredClasses(cfg) {
        var out = ["qol-hm"];
        var len = _int(cfg.CUSTOM_HITMARKER_SIZE, LENGTH);
        var critLen = _int(cfg.CUSTOM_HITMARKER_CRIT_SIZE, LENGTH);
        var thick = _int(cfg.CUSTOM_HITMARKER_THICKNESS, THICKNESS);
        var off = _int(cfg.CUSTOM_HITMARKER_OFFSET, OFFSET);
        var col = _palette(cfg.CUSTOM_HITMARKER_COLOR);
        var critCol = _palette(cfg.CUSTOM_HITMARKER_CRIT_COLOR);
        if (len !== LENGTH.def) out.push("qol-hm-len-" + len);
        if (critLen !== LENGTH.def) out.push("qol-hm-clen-" + critLen);
        if (thick !== THICKNESS.def) out.push("qol-hm-th-" + thick);
        if (off !== OFFSET.def) out.push("qol-hm-off-" + off);
        if (col !== 0) out.push("qol-hm-col-" + col);
        if (critCol !== 0) out.push("qol-hm-ccol-" + critCol);
        if (_isTrue(cfg.ENABLE_CUSTOM_HITMARKER_SHADOW)) out.push("qol-hm-shadow");
        if (_isTrue(cfg.ENABLE_CUSTOM_HITMARKER_HIDE_GLOW)) out.push("qol-hm-noglow");
        return out;
    }

    FR.register({
        id: "ql_hit_marker",
        enableKey: "ENABLE_CUSTOM_HITMARKER",
        enabledByDefault: false,
        settings: [
            { key: "ENABLE_CUSTOM_HITMARKER", type: "toggle", default: false },
            { key: "ENABLE_CUSTOM_HITMARKER_SHADOW", type: "toggle", default: false },
            { key: "ENABLE_CUSTOM_HITMARKER_HIDE_GLOW", type: "toggle", default: false },
            { key: "CUSTOM_HITMARKER_SIZE", type: "slider", min: LENGTH.min, max: LENGTH.max, step: LENGTH.step, default: LENGTH.def },
            { key: "CUSTOM_HITMARKER_CRIT_SIZE", type: "slider", min: LENGTH.min, max: LENGTH.max, step: LENGTH.step, default: LENGTH.def },
            { key: "CUSTOM_HITMARKER_THICKNESS", type: "slider", min: THICKNESS.min, max: THICKNESS.max, step: THICKNESS.step, default: THICKNESS.def },
            { key: "CUSTOM_HITMARKER_OFFSET", type: "slider", min: OFFSET.min, max: OFFSET.max, step: OFFSET.step, default: OFFSET.def },
            { key: "CUSTOM_HITMARKER_COLOR", type: "palette", default: 0 },
            { key: "CUSTOM_HITMARKER_CRIT_COLOR", type: "palette", default: 0 }
        ],
        create: function(ctx) {
            var _applied = [];

            function _apply(cfg) {
                var root = $.GetContextPanel();
                if (!QOL.utils.IsPanelValid(root)) return;
                var next = desiredClasses(cfg);
                var i;
                for (i = 0; i < _applied.length; i++) {
                    if (next.indexOf(_applied[i]) < 0) root.SetHasClass(_applied[i], false);
                }
                for (i = 0; i < next.length; i++) {
                    if (!root.BHasClass(next[i])) root.SetHasClass(next[i], true);
                }
                _applied = next;
            }

            function _clear() {
                var root = $.GetContextPanel();
                if (QOL.utils.IsPanelValid(root)) {
                    for (var i = 0; i < _applied.length; i++) root.SetHasClass(_applied[i], false);
                }
                _applied = [];
            }

            return {
                onEnable: function() { _apply(ctx.config.all()); },
                onDisable: function() { _clear(); },
                onSettingsChanged: function() { _apply(ctx.config.all()); }
            };
        }
    });
})();
