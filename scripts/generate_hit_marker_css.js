#!/usr/bin/env node
// Generates the Custom Hit Marker rules inside panorama/styles/ability_hud_elements/element_gun.css,
// between the BEGIN/END marker comments.
//
// Panorama CSS cannot read a number from JavaScript, so every selectable hit marker value
// (length, thickness, spacing, color) is a static rule that the ql_hit_marker manifest switches
// on with a class on the HUD root (qol-hm-len-24, qol-hm-th-3, ...). The rules live in the gun
// element's own stylesheet, next to the native hit marker rules they override.
//
// Rules are only generated for values that differ from the native hit marker, because the
// manifest emits no class for a native value. The ranges below must match the ql_hit_marker
// manifest, the compact schema in ql_shared_presets.js and the slider shapes in ui/controls.js;
// tests/hit_marker.test.js checks that they agree.
//
//   node scripts/generate_hit_marker_css.js           rewrite the generated block
//   node scripts/generate_hit_marker_css.js --check   exit 1 when the block is stale

"use strict";

const fs = require("fs");
const path = require("path");

const TARGET = path.join(__dirname, "..", "panorama", "styles", "ability_hud_elements", "element_gun.css");
const BEGIN = "/* ==== BEGIN QOLLOCK Custom Hit Marker (generated by scripts/generate_hit_marker_css.js; do not edit by hand) ==== */";
const END = "/* ==== END QOLLOCK Custom Hit Marker ==== */";

// Native values come from base/ability_hud_elements/element_gun.css:
// hitMarkerWidth 20px, hitMarkerHeight 2px, translate 40px, white hits, yellow crits.
const RANGES = {
    length: { min: 4, max: 40, step: 1, native: 20 },
    thickness: { min: 1, max: 8, step: 1, native: 2 },
    offset: { min: 4, max: 40, step: 1, native: 40 }
};

// Palette index 0 keeps the native colors, so only 1..29 get rules.
const NATIVE_CRIT_GLOW = "0px 0px 10px red";
const OUTLINE_SHADOW = "0px 0px 3px rgba(0, 0, 0, 0.6)";

// Each corner mirrors the native transform, with the native 40px translation replaced by the spacing.
const CORNERS = [
    { id: "TopLeftHitMarker", angle: 45, x: -1, y: -1 },
    { id: "TopRightHitMarker", angle: -45, x: 1, y: -1 },
    { id: "BottomLeftHitMarker", angle: -45, x: -1, y: 1 },
    { id: "BottomRightHitMarker", angle: 45, x: 1, y: 1 }
];

function loadPalette() {
    const src = fs.readFileSync(path.join(__dirname, "..", "panorama", "scripts", "ql_utils.js"), "utf8");
    const match = /const QOL_WASH_COLOR_PALETTE\s*=\s*\[([\s\S]*?)\]/.exec(src);
    if (!match) throw new Error("QOL_WASH_COLOR_PALETTE not found in ql_utils.js");
    const colors = [];
    const re = /"([^"]*)"/g;
    let m;
    while ((m = re.exec(match[1])) !== null) colors.push(m[1]);
    if (colors.length !== 30) throw new Error("Expected 30 palette entries, found " + colors.length);
    return colors;
}

// Values the UI can produce for a range, excluding the native one.
function values(range) {
    const out = [];
    for (let n = range.min; n <= range.max; n += range.step) if (n !== range.native) out.push(n);
    return out;
}

function px(n) {
    return n + "px";
}

function build() {
    const palette = loadPalette();
    const hit = ".show_hit_marker .hit_marker";
    const crit = ".show_crit_hit_marker .hit_marker";
    const out = [BEGIN];
    const rule = (selector, declaration) => out.push(selector + " { " + declaration + " !important; }");

    // Hit rules first, crit rules after them: a crit shows both state classes, so on equal
    // specificity the later (crit) rule must win.
    for (const n of values(RANGES.length)) rule(".qol-hm-len-" + n + " " + hit, "width: " + px(n));
    for (let i = 1; i < palette.length; i++) rule(".qol-hm-col-" + i + " " + hit, "background-color: " + palette[i]);

    for (const n of values(RANGES.thickness)) {
        out.push(".qol-hm-th-" + n + " " + hit + ", .qol-hm-th-" + n + " " + crit + " { height: " + px(n) + " !important; }");
    }

    for (const n of values(RANGES.offset)) {
        for (const c of CORNERS) {
            const tx = (c.x < 0 ? "-" : "") + px(n);
            const ty = (c.y < 0 ? "-" : "") + px(n);
            rule(".qol-hm-off-" + n + " #" + c.id + ".hit_marker",
                "transform: rotateZ(" + c.angle + "deg) translateX(" + tx + ") translateY(" + ty + ")");
        }
    }

    rule(".qol-hm-shadow " + hit, "box-shadow: " + OUTLINE_SHADOW);

    for (const n of values(RANGES.length)) rule(".qol-hm-clen-" + n + " " + crit, "width: " + px(n));
    for (let i = 1; i < palette.length; i++) rule(".qol-hm-ccol-" + i + " " + crit, "background-color: " + palette[i]);

    // Keeps the native crit glow when the hit-state outline shadow is on, then lets
    // "Crit Glow off" remove it while still honoring the outline shadow.
    rule(".qol-hm " + crit, "box-shadow: " + NATIVE_CRIT_GLOW);
    rule(".qol-hm-noglow " + crit, "box-shadow: 0px 0px 0px #00000000");
    rule(".qol-hm-noglow.qol-hm-shadow " + crit, "box-shadow: " + OUTLINE_SHADOW);

    out.push(END);
    return out.join("\n");
}

// Replace the generated block in the stylesheet text, or append it when the markers are absent.
function apply(source, block) {
    const start = source.indexOf(BEGIN);
    const end = source.indexOf(END);
    if (start >= 0 && end > start) return source.slice(0, start) + block + source.slice(end + END.length);
    if (start >= 0 || end >= 0) throw new Error("element_gun.css has only one of the hit marker markers");
    return source.replace(/\s*$/, "\n\n") + block + "\n";
}

function main() {
    const source = fs.readFileSync(TARGET, "utf8");
    const next = apply(source, build());
    if (process.argv.includes("--check")) {
        if (next !== source) {
            console.error("element_gun.css hit marker block is out of date. Run: node scripts/generate_hit_marker_css.js");
            process.exit(1);
        }
        console.log("element_gun.css hit marker block is up to date.");
        return;
    }
    fs.writeFileSync(TARGET, next);
    console.log("Updated " + path.relative(process.cwd(), TARGET) + " (" + build().split("\n").length + " lines in the generated block).");
}

if (require.main === module) main();
module.exports = { build, apply, values, RANGES, TARGET, BEGIN, END };
