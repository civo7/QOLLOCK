"use strict";

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const dimension = 360;
const number = value => String(Number(value.toFixed(4)));

function renderReferences(points, kind, scale = 100) {
    const factor = scale / 100;
    const shapes = points.map(([u, v, underground]) => {
        if (![u, v].every(value => Number.isFinite(value) && value >= 0 && value <= 1)) {
            throw Error("Invalid minimap reference coordinate");
        }
        const x = u * dimension, y = v * dimension;
        const opacity = underground && kind !== "crates" ? ' opacity="0.5"' : "";
        let shape;
        if (kind === "crates") {
            const side = 2 * factor;
            shape = `<rect x="${number(x - side / 2 - 1)}" y="${number(y - side / 2 - 1)}" width="${number(side + 2)}" height="${number(side + 2)}" fill="#2A2100" fill-opacity="0.45"/>` +
                `<rect x="${number(x - side / 2)}" y="${number(y - side / 2)}" width="${number(side)}" height="${number(side)}" fill="#FFD54A" fill-opacity="0.75" stroke="#2A2100" stroke-opacity="0.45" stroke-width="1"/>`;
        } else if (kind === "statues") {
            const side = 3 * factor + 1;
            shape = `<rect x="${number(x - side / 2)}" y="${number(y - side / 2)}" width="${number(side)}" height="${number(side)}" fill="#FACC15" stroke="#000000" stroke-width="1" transform="rotate(45 ${number(x)} ${number(y)})"/>`;
        } else {
            const radius = ((kind === "tough_crates" ? 5.4 : 3.5) * factor + 1) / 2;
            const color = kind === "tough_crates" ? "#3B82F6" : "#4ADE80";
            shape = `<circle cx="${number(x)}" cy="${number(y)}" r="${number(radius)}" fill="${color}" stroke="#000000" stroke-width="1"/>`;
        }
        return `  <g${opacity}>${shape}</g>`;
    });
    return `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 360 360">\n` +
        `<!-- Generated by scripts/generate_minimap_reference_images.js; ${points.length} ${kind} references at ${scale}%. -->\n` +
        shapes.join("\n") + "\n</svg>\n";
}

function generateImages() {
    const context = { QOL: {} };
    vm.createContext(context);
    for (const file of ["ql_minimap_crate_data.js", "ql_minimap_loot_data.js"]) {
        vm.runInContext(fs.readFileSync(path.join(root, "panorama/scripts", file), "utf8"), context);
    }
    return Object.fromEntries(["crates", "tough_crates", "snacks", "statues"].flatMap(kind =>
        [50, 75, 100, 125, 150].map(scale => [
            `minimap_references_${kind}${scale === 100 ? "" : "_" + scale}.vsvg`,
            renderReferences(kind === "crates" ? context.CRATE_DATA.dl_midtown.crates : context.QOL.minimapLootData[kind], kind, scale)
        ])));
}

if (require.main === module) {
    for (const [file, contents] of Object.entries(generateImages())) {
        fs.writeFileSync(path.join(root, "panorama/images/qollock", file), contents);
    }
}

module.exports = { generateImages, renderReferences };
